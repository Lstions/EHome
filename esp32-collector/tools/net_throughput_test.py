#!/usr/bin/env python3
"""net_throughput_test.py -- 5-channel x 100 Hz full-fit network soak for EHome nodes.

Goal
----
Prove that the network configuration in esp32-collector/sdkconfig.defaults can
carry the full fit (S3: 5 channels x 100 Hz = 500 DataReports/s, ~300 B each =
~150 KB/s raw payload) with:
  * drop rate  < 0.1 %
  * MQTT stays connected (no disconnect / reconnect)
  * end-to-end latency p99 < 200 ms

How it works
------------
1. Connects to the MQTT broker as the *server side* (the same thing the Go
   backend does) and subscribes to ``nodes/<node>/up`` and
   ``nodes/<node>/down``.
2. Publishes a ConfigManifest (5 channels, interval_ms=10) to
   ``nodes/<node>/down``, which the firmware applies transactionally.  Each
   channel is a real hardware channel with DMA disabled and a tiny UART
   read size, so the scheduler performs real bus transactions.  The point of
   the manifest is to drive the firmware's *scheduler* at 100 Hz; the wire
   payload is generated by the node's own DataReports.
3. For the configured soak window it counts DataReports per channel, watches
   for sequence gaps (drop rate), and measures MQTT receive-time latency using
   the node's own ``timestamp_us`` field (esp_timer_get_time, monotonic, not
   wall clock).  Clock offset is removed by using the *minimum* observed
   received-minus-timestamp difference as the reference.

   Latency convention (read before quoting a number): the reported p99 is the
   *additional* one-way delay above the best observed case (jitter + queueing),
   NOT the absolute device->host propagation time -- min(recv - ts) absorbs any
   constant offset, and host and device have no shared time base without NTP.
   That is the right gate for a 100 Hz control loop (is queueing/jitter under
   control?), but do not report it as end-to-end propagation latency.
4. Reports pass/fail against the three acceptance criteria.

Usage
-----
  python3 tools/net_throughput_test.py \
      --broker 192.168.20.6 --port 1883 --node 1001 \
      --duration 60 [--channels 5] [--hz 100] [--json out.json]

Defaults assume the firmware's CONFIG_COLLECTOR_NODE_ID and that the host can
reach the MQTT broker (e.g. the production EMQX at 192.168.20.6:1883).

Wire format
-----------
protobuf-style TLV, first byte = message type.  Encoded here exactly as
backend/internal/nodemgr/sender_snapshot.go encodes ConfigManifest:
  manifest: field 1 = manifest_id (str), field 8 = sync_id (str),
            field 3 = template (sub), field 4 = channel (sub)
  template: field 1 = id, field 2 = write_data, field 3 = read_length,
            field 4 = delay_ms
  channel:  field 1 = id, field 2 = hardware_id, field 3 = template_ids
            (repeated varint), field 4 = interval_ms, field 5 = enabled,
            field 6 = bus_type (1=UART), field 7 = bus_config
  DataReport: field 1 = channel_id, field 2 = timestamp_us, field 3 = sequence,
            field 4 = raw payload, field 5 = error_code

Requires: paho-mqtt >= 2.0 (``python3 -m pip install paho-mqtt``).
Note: on this host paho is available in the IDF 6.0 python env
(/home/sun/.espressif/python_env/idf6.0_py3.14_env/bin/python) or install it
into any python3.
"""

