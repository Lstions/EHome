#pragma once

/* ============================================================================
 * 启动熔断（boot guard）— 2026-10-05
 * ============================================================================
 *
 * 为什么需要它
 * ------------
 * 2026-10-04 实测：满资源占用下打开日志上报，S3 节点在 506 秒内 PANIC 重启 11 次。
 * 真正危险的不是"崩了一次"，而是**自持**：日志开关的配置随 ConfigManifest 持久化，
 * 设备每次重启后都会**重新应用同一个配置**，于是再次崩溃 —— 无限重启循环。
 * 现有代码里没有任何熔断：
 *   - CONFIG_BOOTLOADER_APP_ROLLBACK_ENABLE=n（不做 OTA 回滚）；
 *   - 无连续启动计数、无安全模式、无降级启动。
 * 也就是说：**一个坏配置就能让远程部署的节点永久躺平，只能靠人工接触设备恢复。**
 *
 * 判据：两次启动的**间隔**，而不是上一次的存活时长
 * -------------------------------------------------
 * 第一版按"上一次启动存活 < 60s 才算短命启动"来判，**这是错的**。
 * 实测本设备 48 次崩溃的 uptime 分布：
 *
 *     min = 13s    avg = 229s    max = 3341s
 *     uptime >= 60s 的有 38 次，占 79%
 *
 * 也就是说，绝大多数真实崩溃发生在启动 60 秒**之后**。按存活时长判会把它们全部漏掉 ——
 * 一个"每次活 200 秒就崩"的循环永远不会触发熔断，而那恰恰是最常见的形态。
 *
 * 现在改为记录每次启动的时刻（esp_rtc_get_time_us()，RTC 计数器**跨 CPU 复位不归零**），
 * 启动时算"距上次启动过了多久"：
 *
 *     delta < BOOT_GUARD_LOOP_WINDOW_SEC  -> 计一次快速重启（无论上次活了多久）
 *     delta >= 窗口                        -> 计数重置为 1（正常重启）
 *
 * 这个判据与"单次存活多久"无关，因此对上面那种长存活崩溃同样有效：
 *   - 事故现场 506 秒 11 次重启，间隔约 50 秒 => 连续 3 次迅速达标；
 *   - "稳定运行一周后正常重启一次"的间隔是 1 周 >> 窗口 => 不误判。
 *
 * 掉电会清零 RTC 计数器，但掉电**不应该**算作重启循环，所以这是正确行为。
 * 同时 NVS 也保存一份计数并与 RTC 取较大者，避免反复上电绕过熔断。
 *
 * 安全模式的行为
 * --------------
 * 1) **只关可选特性，不动核心能力**：设备在安全模式下仍然联网、上报心跳、
 *    接受配置、执行命令，只关闭"会把同一条连接流量放大数倍"的可选特性
 *    （当前是日志上报）。这样运维仍然能通过网络诊断和恢复设备。
 * 2) **覆盖服务端配置**：见 main/app_callbacks.c 的 tx_apply_log_stream()。
 *    这是止血的关键 —— 否则熔断只会让重启变慢，不会让它停。
 * 3) **退出条件是"持续健康"**：既要有一次服务端往返（证明链路通），
 *    又要稳定运行超过 BOOT_GUARD_SAFE_MODE_MIN_DWELL_MS。
 *    只有一次握手就恢复是不够的 —— 设备可能在启动几秒内就完成一次配置事务，
 *    但那不能证明它已脱离崩溃循环，立刻恢复可选特性会重新冲进循环。
 */

#include <stdbool.h>
#include <stdint.h>

/* 两次启动的间隔小于此值，即视为"快速重启"（计入重启循环）。
 *
 * 取 60s 的依据：事故现场 506 秒内 11 次重启 => 平均间隔约 46 秒，全部 < 60s；
 * 而正常运维重启（升级、手动重启）之后设备通常稳定运行远超过 60 秒。
 * 注意这个阈值针对的是**间隔**，不是存活时长 —— 见文件头说明。 */
#define BOOT_GUARD_LOOP_WINDOW_SEC 60U

/* 连续多少次快速重启后进入安全模式。
 * 取 3：2 次可能只是偶发（恰好赶上网络抖动或手动重启），
 * 3 次已足以说明"每次启动都撞同一堵墙"。 */
#define BOOT_GUARD_LOOP_THRESHOLD 3U

/* 安全模式解除前，要求设备稳定运行的最短时间。
 *
 * 取 120s：必须**显著大于** BOOT_GUARD_LOOP_WINDOW_SEC（60s），
 * 否则可能出现"刚解除降级就又崩"的振荡。
 * 同时它也大于事故现场的最长崩溃 uptime 区间（23~112s），
 * 所以"活过 120 秒"对这台设备而言确实是一个有意义的健康信号。 */
#define BOOT_GUARD_SAFE_MODE_MIN_DWELL_MS 120000U

/**
 * 初始化：读上次启动时刻 -> 判定是否快速重启 -> 更新计数 -> 决定是否进入安全模式。
 *
 * 必须在 nvs_flash_init() 之后、启动各子系统之前调用（建议紧随 crash_diag_init()）。
 * 幂等。
 *
 * @return 进入安全模式返回 true，否则 false。
 */
bool boot_guard_init(void);

/** 当前是否处于安全模式。未初始化时返回 false。 */
bool boot_guard_in_safe_mode(void);

/** 进入安全模式的原因（可读字符串，永不返回 NULL；未进入时返回 ""）。 */
const char *boot_guard_safe_mode_reason(void);

/** 连续快速重启计数（用于诊断上报）。 */
uint32_t boot_guard_fast_boot_count(void);

/**
 * 周期性刷新：检查是否满足"持续健康"从而可以退出安全模式。
 * 由 status_task（1s 周期）与内部定时器共同调用；只读时间，无 flash 代价。
 */
void boot_guard_tick(void);

/**
 * 启动内部周期定时器（esp_timer，不新建任务）。
 * 幂等；在 boot_guard_init() 之后调用一次即可。
 * 即使定时器创建失败，status_task 的 1s 调用仍会驱动状态机。
 */
void boot_guard_start_watchdog(void);

/**
 * 由服务端接触回调：设备已证明链路可用（完成一次端到端配置事务）。
 *
 * - 正常模式下：清零快速重启计数；
 * - 安全模式下：**只记录**"已见到健康"，实际解除由 boot_guard_tick()
 *   在满足 BOOT_GUARD_SAFE_MODE_MIN_DWELL_MS 后进行。
 */
void boot_guard_notify_server_contact(void);