// Package backfill 把老 unified_data 的历史行回填成帧表（telemetry_frame）的帧级编码。
//
// 契约全文：docs/设计/老数据迁移到帧表-分析与契约-2026-11-07.md（§4 是设计，§6 是验收）。
//
// ============ 这个包解决什么问题 ============
//
// L1/L2 无条件启用后，**新**数据自动进帧表；但**老**数据仍是 unified_data 里
// 一帧拆成 29 行的形态 —— 生产 72,695,394 行 / 3,419,991 帧 / 15 GB。
// 把它们按帧重新编码后约 463 MB，净释放约 14.5 GB。
//
// ============ 三条硬约束（决定了整个设计）============
//
//  1. **不能逐行处理**：unified_data 一行是一个**字段**，而帧表一行是一**帧**。
//     必须先按 (device_id, timestamp) 把整帧的行取齐，才能交给编码器。
//     逐行处理会让每一行变成一帧 ⇒ 帧数放大 29 倍、压缩率归零。
//
//  2. **必须断点续跑**：3.42M 帧 / 20~40 分钟。滚动发布、重启、OOM 都会打断它。
//     断点落在数据库（telemetry_backfill_progress，见 datalifecycle 包），
//     不用进程内变量 —— 那活不过重启。
//
//  3. **绝不阻塞启动**：整个回填是后台 goroutine，服务 ready 与回填解耦。
//     维护页可以显示"回填中"，但业务接口不等它。
//
// ============ 复用而不是重写 ============
//
// 编码链路（slot 派生 / 量化 / 增量链 / 位打包）**全部复用 internal/telemetry**：
//
//	telemetry.NewEncoder   增量链 + 关键帧判定
//	telemetry.DBSlots      slot 字典（跨进程稳定）
//	telemetry.SpecFor      字段量化规格（精度唯一真源）
//
// 本包只做三件 telemetry 不做的事：**按帧聚合行**、**断点续跑**、**超量程原文保留**。
// 自己再写一遍增量编码必然与线上编码漂移，那种漂移只在解码时暴露 —— 不能接受。
//
// ============ 一条容易踩的语义坑（务必读）============
//
// 2026-11-06 起 L1 生效，「值不变不入库」⇒ unified_data 里**新**的帧只含变化字段，
// 一帧可能有 3 个字段而不是 29 个。因此回填出来的 slot 不是"每设备 1 个"，
// device14 实测会有约 7,351 个不同字段集合 ⇒ 约 7,351 个 slot。
//
// 这不是缺陷：解码器按**字段**累加状态（不是按 slot），稀疏帧的 keyframe 只设置
// 它自己那几个字段，其余字段保留上一帧的值，语义完全正确（详见 decoder 的
// DecodeRange）。验收 §6.6 要求 slot < 10,000 行，正是在给这个数字留余量。
